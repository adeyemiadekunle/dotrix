// Dotrix mounts one document-level theme. Older Firefox ESR lacks CSS @scope;
// generate equivalent root selectors without editing Astryx's canonical outputs.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const directory = new URL("../src/theme/", import.meta.url);
const output = new URL("dotrix-compat.css", directory);
const check = process.argv.includes("--check");
const sheets = ["dotrix.css", "dotrix-reduced.css"].map((file) => {
  const source = new URL(file, directory);
  const root = postcss.parse(readFileSync(source, "utf8"), { from: fileURLToPath(source) });
  root.walkAtRules("scope", (scope) => {
    const match = scope.params.match(/^\(\[data-astryx-theme="([\w-]+)"\]\) to \(\[data-astryx-theme\]\)$/);
    if (!match) throw new Error(`Unrecognized Astryx theme scope: ${scope.params}`);
    const theme = `:root[data-astryx-theme="${match[1]}"]`;
    scope.walkRules((rule) => {
      rule.selectors = rule.selectors.map((selector) => (selector.includes(":scope") ? selector.replaceAll(":scope", theme) : `:where(${theme}) ${selector}`));
    });
    scope.replaceWith(...scope.nodes);
  });
  root.walkComments((comment) => comment.remove());
  return root.toString().trim();
});
const css = "/* Generated by scripts/theme-compat.mjs from the canonical Astryx theme CSS. Do not edit. */\n" + sheets.join("\n\n") + "\n";
if (check) {
  if (readFileSync(output, "utf8") !== css) throw new Error("Theme compatibility CSS is stale; run theme:build");
  console.log("Root theme compatibility CSS is up to date.");
} else {
  writeFileSync(output, css);
  console.log("Generated root theme compatibility CSS.");
}
