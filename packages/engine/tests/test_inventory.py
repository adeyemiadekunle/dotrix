"""The repository inventory's classification: what a path is, its domains, and whether it's read."""
from dotrix_engine.inventory import DOMAINS, GAP_HINTS, classify


def test_paths_are_classified_by_what_they_are() -> None:
    lock = classify("pnpm-lock.yaml", size=10)
    assert "lockfile" in lock.kinds and lock.domains == ("dependencies",) and lock.status == "pending"
    source = classify("apps/backend/src/app/service.py", size=10)
    assert source.language == "Python" and "source" in source.kinds and "architecture" in source.domains
    test = classify("apps/web/src/core/utils.test.ts", size=10)
    assert "test" in test.kinds and "quality" in test.domains and "source" not in test.kinds
    ci = classify(".github/workflows/ci.yml", size=10)
    assert set(ci.domains) == {"delivery", "quality"}
    assert "data" in classify("apps/backend/migrations/versions/0001_init.py", size=10).domains
    assert "apis" in classify("apps/backend/src/app/router.py", size=10).domains
    assert "design" in classify("apps/web/src/screens/Chat.tsx", size=10).domains
    assert "decisions" in classify("docs/adr/0003-use-postgres.md", size=10).domains
    assert "product" in classify("README.md", size=10).domains
    assert "non_functional" in classify("SECURITY.md", size=10).domains
    assert "tooling" in classify("apps/backend/alembic.ini", size=10).domains


def test_what_isnt_read_stays_listed_with_why() -> None:
    assert classify("node_modules/x/index.js", size=10).reason == "Vendored third-party code"
    assert classify("web/dist/app.js", size=10).status == "excluded"
    assert classify("src/schema.ts", size=10, head=b"// @generated by openapi-typescript\n").status == "excluded"
    logo = classify("web/logo.png", size=10)
    assert logo.status == "excluded" and "asset" in logo.kinds and logo.domains == ("design",)
    assert classify("data/blob.dat", size=10, head=b"ab\0cd").reason == "Binary: listed, not read"
    assert classify("fixtures/huge.json", size=2_000_000).status == "excluded"
    sub = classify("vendor-lib", size=0, mode="160000")
    assert sub.status == "inaccessible" and "submodule" in sub.reason.lower()
    assert classify("link", size=5, mode="120000").status == "excluded"


def test_every_domain_names_its_gap() -> None:
    assert set(GAP_HINTS) == set(DOMAINS) and len(DOMAINS) == 12


async def test_a_checkout_that_moves_while_read_is_read_again(tmp_path, monkeypatch) -> None:
    import subprocess

    from dotrix_engine import inventory

    def git(*args: str) -> str:
        return subprocess.run(["git", "-C", str(tmp_path), "-c", "user.email=a@b.c", "-c", "user.name=A", *args],
                              check=True, capture_output=True, text=True).stdout.strip()

    git("init", "-q")
    (tmp_path / "a.py").write_text("A = 1\n")
    git("add", "-A")
    git("commit", "-qm", "one")
    read, calls = inventory._read, []

    async def moving(root, commit):
        calls.append(commit)
        if len(calls) == 1:  # a sync lands halfway through the first read
            (tmp_path / "b.py").write_text("B = 2\n")
            git("add", "-A")
            git("commit", "-qm", "two")
        return await read(root, commit)

    monkeypatch.setattr(inventory, "_read", moving)
    taken = await inventory.take_inventory(tmp_path)
    assert taken.commit == git("rev-parse", "HEAD") and len(calls) == 2
    assert [p.path for p in taken.paths] == ["a.py", "b.py"] and taken.paths[0].size == 6
